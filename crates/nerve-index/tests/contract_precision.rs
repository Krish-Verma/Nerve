//! Precision for C1, C2 and C3, measured **per rule** against ground truth written first
//! (Slices 13b and 13c).
//!
//! Three rules, three tables, **no combined number**. Rows 2a, 9b, 10a and 10b each established
//! that and it is not reopened here: a single "contract precision" figure would let a rule with a
//! hundred easy declarations hide a rule with three hard ones, and the three rules read different
//! files in different languages with different failure modes.
//!
//! The gate is **FP = 0**. Recall is computed and printed and is **not** gated, for the reason rows
//! 2a and 9b give: a recall gate is met by guessing.
//!
//! # What counts as what
//!
//! Ground truth is `fixtures/contracts-npm/ground_truth.json`,
//! `fixtures/contracts-exports/ground_truth.json` and
//! `fixtures/contracts-python/ground_truth.json`. All three are hand-written, all three were
//! written before the resolver existed, and none is produced by running Nerve — a file generated by
//! the thing it grades measures nothing but self-consistency.
//!
//! Declarations are keyed by two things that identify a declaration and that cannot be obtained
//! only by running the code under test. For C1 and C3 that is `(manifest section, dependency key)`;
//! for C2 it is `(importing file, import specifier)`, because the same specifier written in two
//! files is two declarations. [`KeyBy`] is which of the two a document uses, and it is stated in
//! the document rather than inferred.
//!
//! - **TP** — a ground-truth `link` row for which the scan produced a link to the named target with
//!   the named `resolution_method` and the named `form`.
//! - **FP** — any produced link that is not a TP: a link for a row whose verdict is `unresolved` or
//!   `unsupported`, a link for a declaration no ground-truth row mentions, a link to the wrong
//!   target, by the wrong method, or in the wrong form — and a *second* link for a declaration the
//!   oracle says produces one.
//! - **FN** — a ground-truth `link` row with no produced link, **and** every `declined_true_link`
//!   row: a declaration that names a real target through a form outside the enumerated syntax. That
//!   is 10b's `Views.handle` rule — a rule that declines a shape declares the miss rather than
//!   quietly resolving it — and it is why recall is below 1 in all three tables.
//!
//! `unresolved` and `unsupported` rows are not "misses". They are declarations whose correct answer
//! is *no link*, and producing one for them is a false positive rather than a lost recall point.


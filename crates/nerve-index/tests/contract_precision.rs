/// **C2's table.** Its own fixture, its own ground truth, its own gate. Never summed with either
/// of the other two.
///
/// This is the one rule in row 13 that reaches a file entity inside the target, so the table has
/// two anti-vacuity floors rather than one: enough true positives that the numbers describe
/// something, and at least one link that actually carries a foreign `target_entity_id`. A C2 table
/// full of path-only links would satisfy every count above and prove nothing about the thing the
/// rule exists to do.
#[test]
fn c2_npm_export_resolution_precision() {
    let dir = tempfile::tempdir().unwrap();
    let host = place(dir.path(), "contracts-exports", "host");
    let neighbours: Vec<PathBuf> = [
        "pkg-map",
        "pkg-string",
        "pkg-legacy",
        "twin-a",
        "twin-b",
        "pkg-unregistered",
    ]
    .iter()
    .map(|name| place(dir.path(), "contracts-exports", name))
    .collect();

    nerve_index::init_with_project_id(&host, Some(&project_id(21))).unwrap();
    nerve_index::index_repository(&host).unwrap();
    for (offset, root) in neighbours.iter().enumerate() {
        nerve_index::init_with_project_id(root, Some(&project_id(22 + offset as u8))).unwrap();
        nerve_index::index_repository(root).unwrap();
    }
    // `pkg-unregistered` is deliberately left out, and it is the last of the six.
    for root in &neighbours[..5] {
        register(&host, root);
    }

    let truth = ground_truth("contracts-exports");
    let scan = scan_of(&host);
    let table = measure(
        "C2 npm_export_resolution",
        "contracts-exports",
        &truth,
        &scan,
        ContractRule::NpmExportResolution,
        KeyBy::FileAndSpecifier,
    );
    table.report();

    // The tally §9.1 asks for, against the hand-written totals — **per rule**, because this scan
    // also produced C1 links from the same manifest and adding the two would be the combined
    // number three rows have now refused.
    let totals = &truth["totals"];
    let c2_links = scan.links_of(ContractRule::NpmExportResolution).count();
    assert_eq!(
        c2_links,
        totals["expected_links"].as_u64().unwrap() as usize
    );
    assert_eq!(
        scan.unresolved_of(ContractRule::NpmExportResolution)
            .count(),
        totals["expected_unresolved"].as_u64().unwrap() as usize
    );
    assert_eq!(
        scan.unsupported_of(ContractRule::NpmExportResolution)
            .count(),
        totals["expected_unsupported"].as_u64().unwrap() as usize
    );

    // The gate.
    assert_eq!(
        table.false_positives.len(),
        totals["expected_false_positives"].as_u64().unwrap() as usize,
        "false positives: {:?}",
        table.false_positives
    );
    assert_eq!(table.false_positives.len(), 0, "the gate is FP = 0");
    assert_eq!(
        table.false_negatives.len(),
        totals["expected_false_negatives"].as_u64().unwrap() as usize,
        "false negatives: {:?}",
        table.false_negatives
    );

    // Anti-vacuity, both halves.
    assert!(table.true_positives >= 5, "{table:?}");
    let with_entity = scan
        .links_of(ContractRule::NpmExportResolution)
        .filter(|link| link.target_entity_id.is_some())
        .count();
    assert!(
        with_entity >= 5,
        "only {with_entity} C2 links name an entity in the neighbour; the rule exists to reach one"
    );
    assert_eq!(
        c2_links - with_entity,
        totals["links_with_no_target_entity"].as_u64().unwrap() as usize,
        "a link with a path and no entity is `target_partially_indexed`, and the oracle counts them"
    );
}

/// **No combined number exists.** Asserted over the ground truth documents themselves.
///
/// The three tables above are separate values with separate gates and there is no method on
/// [`PrecisionTable`] that adds one to another — but the durable risk is a *document* growing a
/// summary row, so the oracles are scanned for one. Each file must declare exactly one rule, and
/// none may carry a total that spans another.
#[test]
fn neither_ground_truth_document_carries_a_combined_number() {
    let mut rules = BTreeSet::new();
    for fixture in ["contracts-npm", "contracts-exports", "contracts-python"] {
        let truth = ground_truth(fixture);
        let rule = truth["rule"].as_str().unwrap().to_string();
        assert!(
            rules.insert(rule.clone()),
            "{fixture} claims a rule another oracle already claims"
        );
        assert!(
            truth["note"]
                .as_array()
                .unwrap()
                .iter()
                .any(|line| line.as_str().unwrap().contains("NEVER SUMMED")),
            "{fixture} no longer states that its table is not summed"
        );
        let totals = truth["totals"].as_object().unwrap();
        for key in totals.keys() {
            assert!(
                !key.contains("combined") && !key.contains("overall") && !key.contains("total_all"),
                "{fixture} grew a combined total: {key}"
            );
        }
    }
    assert_eq!(rules.len(), 3, "the three oracles are not three rules");
}
